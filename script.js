const STORAGE_KEY = "indicatorValidationReviews_v1";
const ANSWERS = ["Agree", "Disagree", "Not sure", "Not applicable"];
let currentIndex = 0;
let reviews = loadReviews();

const $ = (id) => document.getElementById(id);
const select = $("indicatorSelect");

function loadReviews() { try { return JSON.parse(localStorage.getItem(STORAGE_KEY) || "{}"); } catch (e) { return {}; } }
function persist() { localStorage.setItem(STORAGE_KEY, JSON.stringify(reviews)); }
function current() { return INDICATORS[currentIndex]; }
function safe(value) { return String(value ?? ""); }

function init() {
  INDICATORS.forEach((item, i) => {
    const option = document.createElement("option");
    option.value = String(i);
    option.textContent = `${item.id} — ${item.criterion}`;
    select.appendChild(option);
  });
  select.addEventListener("change", () => { saveCurrentToMemory(); currentIndex = Number(select.value); render(); });
  $("prevBtn").addEventListener("click", () => navigate(-1));
  $("nextBtn").addEventListener("click", () => navigate(1));
  $("saveBtn").addEventListener("click", saveReview);
  $("exportAllBtn").addEventListener("click", exportAll);
  document.querySelectorAll('input[name="recommendation"]').forEach(el => el.addEventListener("change", toggleOther));
  $("judgeName").addEventListener("change", saveCurrentToMemory);
  $("judgeAffiliation").addEventListener("change", saveCurrentToMemory);
  render();
}
function navigate(delta) { saveCurrentToMemory(); currentIndex = Math.max(0, Math.min(INDICATORS.length - 1, currentIndex + delta)); render(); }
function render() {
  const item = current(), saved = reviews[item.id] || {};
  select.value = String(currentIndex);
  $("areaBadge").textContent = item.area;
  $("criterionTitle").textContent = item.criterion;
  $("indicatorText").textContent = item.indicator;
  $("indicatorPosition").textContent = `Indicator ${currentIndex + 1} of ${INDICATORS.length}`;
  $("checklist").innerHTML = "";
  item.questions.forEach((q, i) => {
    const wrapper = document.createElement("div"); wrapper.className = "question";
    const p = document.createElement("p"); p.textContent = `${i + 1}. ${q}`; wrapper.appendChild(p);
    const row = document.createElement("div"); row.className = "choice-row";
    ANSWERS.forEach(answer => {
      const label = document.createElement("label"); label.className = "choice";
      const input = document.createElement("input"); input.type = "radio"; input.name = `q${i}`; input.value = answer;
      input.checked = (saved.answers || [])[i] === answer;
      input.addEventListener("change", saveCurrentToMemory);
      label.append(input, document.createTextNode(answer)); row.appendChild(label);
    });
    wrapper.appendChild(row); $("checklist").appendChild(wrapper);
  });
  const recs = $("recommendations"); recs.innerHTML = '<legend class="sr-only">Recommendation</legend>';
  item.recommendations.forEach((rec, i) => {
    const label = document.createElement("label"); const input = document.createElement("input");
    input.type = "radio"; input.name = "recommendation"; input.value = rec;
    input.checked = saved.recommendation === rec;
    input.addEventListener("change", () => { toggleOther(); saveCurrentToMemory(); });
    label.append(input, document.createTextNode(rec)); recs.appendChild(label);
  });
  $("otherRecommendation").value = saved.otherRecommendation || "";
  $("rationale").value = saved.rationale || "";
  $("ambiguousTerms").value = saved.ambiguousTerms || "";
  $("revisionSuggestion").value = saved.revisionSuggestion || "";
  $("judgeName").value = saved.judgeName || localStorage.getItem("validationJudgeName") || "";
  $("judgeAffiliation").value = saved.judgeAffiliation || localStorage.getItem("validationJudgeAffiliation") || "";
  toggleOther(); $("prevBtn").disabled = currentIndex === 0; $("nextBtn").disabled = currentIndex === INDICATORS.length - 1;
  $("statusMessage").textContent = "";
  updateProgress();
  ["otherRecommendation", "rationale", "ambiguousTerms", "revisionSuggestion"].forEach(id => $(id).addEventListener("input", saveCurrentToMemory));
}
function toggleOther() {
  const rec = document.querySelector('input[name="recommendation"]:checked');
  $("otherWrap").classList.toggle("hidden", !(rec && rec.value.startsWith("Other")));
}
function collectCurrent() {
  const item = current();
  const answers = item.questions.map((_, i) => document.querySelector(`input[name="q${i}"]:checked`)?.value || "");
  const recommendation = document.querySelector('input[name="recommendation"]:checked')?.value || "";
  return {
    indicatorId: item.id, area: item.area, criterion: item.criterion, indicator: item.indicator,
    judgeName: $("judgeName").value.trim(), judgeAffiliation: $("judgeAffiliation").value.trim(),
    answers, recommendation, otherRecommendation: $("otherRecommendation").value.trim(),
    rationale: $("rationale").value.trim(), ambiguousTerms: $("ambiguousTerms").value.trim(),
    revisionSuggestion: $("revisionSuggestion").value.trim(), reviewedAt: new Date().toISOString()
  };
}
function saveCurrentToMemory() {
  if (!current()) return;
  const record = collectCurrent();
  // Do not mark as reviewed until the judge has made a recommendation or answered a checklist item.
  const touched = record.answers.some(Boolean) || Boolean(record.recommendation) || Boolean(record.rationale || record.ambiguousTerms || record.revisionSuggestion);
  if (touched) reviews[current().id] = { ...record, reviewedAt: reviews[current().id]?.reviewedAt || record.reviewedAt };
  localStorage.setItem("validationJudgeName", $("judgeName").value.trim());
  localStorage.setItem("validationJudgeAffiliation", $("judgeAffiliation").value.trim());
  persist(); updateProgress();
}
function updateProgress() {
  const done = INDICATORS.filter(item => reviews[item.id]?.recommendation).length;
  $("progressText").textContent = `${done} of ${INDICATORS.length} reviewed`;
  $("progressBar").style.width = `${done / INDICATORS.length * 100}%`;
  [...select.options].forEach((o, i) => { const item = INDICATORS[i]; o.textContent = `${reviews[item.id]?.recommendation ? "✓ " : ""}${item.id} — ${item.criterion}`; });
}
function csvEscape(value) { let s = Array.isArray(value) ? value.join(" | ") : safe(value); return '"' + s.replace(/"/g, '""') + '"'; }
function download(filename, content) {
  const blob = new Blob([content], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob); const a = document.createElement("a"); a.href = url; a.download = filename; document.body.appendChild(a); a.click(); a.remove(); URL.revokeObjectURL(url);
}
function saveReview() {
  const record = collectCurrent();
  if (!record.judgeName) { $("statusMessage").textContent = "Enter the judge name or ID before saving."; $("judgeName").focus(); return; }
  if (record.answers.some(a => !a)) { $("statusMessage").textContent = "Complete every statement in the consideration checklist before saving."; return; }
  if (!record.recommendation) { $("statusMessage").textContent = "Select a recommendation before saving."; return; }
  if (record.recommendation.startsWith("Other") && !record.otherRecommendation) { $("statusMessage").textContent = "Specify the recommendation selected as “Other”."; return; }
  if (!record.rationale) { $("statusMessage").textContent = "Enter a brief rationale for your recommendation."; $("rationale").focus(); return; }
  record.reviewedAt = new Date().toISOString(); reviews[current().id] = record; persist(); updateProgress();
  $("statusMessage").textContent = "Review saved successfully.";
}
function exportAll() {
  const records = INDICATORS.map(item => reviews[item.id]).filter(Boolean);
  if (!records.length) { $("statusMessage").textContent = "There are no saved reviews to export yet."; return; }
  const headers = ["reviewed_at", "judge_name", "judge_affiliation", "indicator_id", "area", "criterion", "indicator", "recommendation", "other_recommendation", "rationale", "ambiguous_terms", "revision_suggestion", ...INDICATORS[0].questions.map((_, i) => `checklist_${i + 1}`)];
  const rows = records.map(r => [r.reviewedAt, r.judgeName, r.judgeAffiliation, r.indicatorId, r.area, r.criterion, r.indicator, r.recommendation, r.otherRecommendation, r.rationale, r.ambiguousTerms, r.revisionSuggestion, ...r.answers].map(csvEscape).join(","));
  download(`todas_las_revisiones_${new Date().toISOString().slice(0, 10)}.csv`, "\uFEFF" + headers.map(csvEscape).join(",") + "\r\n" + rows.join("\r\n") + "\r\n");
}

